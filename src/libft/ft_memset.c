#include "libft.h"

void	*ft_memset(void *s1, int c, size_t n)
{
	int		i;
	char	c2;
	char	*s2;

	i = 0;
	c2 = c;
	s2 = (char *)s1;
	while (n > 0)
	{
		s2[i++] = c2;
		n--;
	}
	return (s1);
}
